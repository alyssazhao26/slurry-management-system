CREATE TABLE IF NOT EXISTS system_import.slitting_event_categories (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    main_category VARCHAR(160) NOT NULL,
    subcategory VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 100,
    updated_by BIGINT UNSIGNED NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_slitting_event_category (main_category, subcategory),
    INDEX idx_slitting_event_category_active (is_active, display_order)
);

